/* Build the Agent Canvas extension: one self-contained browser ESM file.
 *
 * A Canvas extension is a single module loaded from a Blob URL, so everything
 * it needs — React, the app, the stylesheet, the web fonts — has to be in that
 * one file. Two transforms adapt the app's CSS to living inside Canvas:
 *
 *   1. Every selector is scoped under .assert-ext, and the page-level ones
 *      (:root, html, body, *) are rewritten onto that root, so the extension
 *      cannot restyle Canvas.
 *   2. The fonts index.html loads with a <link> become an @import, since the
 *      extension owns no document head of its own.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

import esbuild from 'esbuild'
import postcss from 'postcss'
import prefixer from 'postcss-prefix-selector'

const here = dirname(fileURLToPath(import.meta.url))
const PACKAGE = join(here, '..', 'extensions', 'assert')
const ROOT_CLASS = '.assert-ext'

// The manifest decides where the bundle goes, so the declared entrypoint and
// the built file cannot drift apart.
const MANIFEST = JSON.parse(readFileSync(join(PACKAGE, 'canvas-extension.json'), 'utf8'))
const OUTFILE = join(PACKAGE, MANIFEST.entrypoint)

// Selectors that mean "the page". Inside the extension they mean our root.
const PAGE_LEVEL = new Set([':root', 'html', 'body'])

function scopeSelector(selector) {
  const trimmed = selector.trim()
  if (PAGE_LEVEL.has(trimmed)) return ROOT_CLASS
  // The universal selectors must reach the root itself as well as its
  // descendants, or box-sizing stops at the boundary.
  if (trimmed === '*') return `${ROOT_CLASS}, ${ROOT_CLASS} *`
  if (trimmed.startsWith('*::')) {
    const pseudo = trimmed.slice(1)
    return `${ROOT_CLASS}${pseudo}, ${ROOT_CLASS} *${pseudo}`
  }
  return null // fall through to the default prefixer behaviour
}

/* index.html stays the single source of truth for which fonts the app uses. */
function fontImport() {
  const html = readFileSync(join(here, 'index.html'), 'utf8')
  const href = html.match(/href="(https:\/\/fonts\.googleapis\.com\/css2[^"]+)"/)?.[1]
  if (!href) throw new Error('no fonts.googleapis.com stylesheet found in index.html')
  return `@import url('${href.replaceAll('&amp;', '&')}');\n`
}

/* The whole point of the scoping pass: a selector that escapes .assert-ext
   restyles Canvas itself, so one is a build failure rather than a warning. */
function assertScoped(css) {
  const loose = []
  postcss.parse(css).walkRules((rule) => {
    if (rule.parent?.type === 'atrule' && rule.parent.name.endsWith('keyframes')) return
    loose.push(...rule.selectors.filter((selector) => !selector.startsWith(ROOT_CLASS)))
  })
  if (loose.length) {
    throw new Error(`${loose.length} selector(s) escaped ${ROOT_CLASS}: ${loose.join(', ')}`)
  }
}

async function buildCss() {
  const source = join(here, 'src', 'styles.css')
  const scoped = await postcss([
    prefixer({
      prefix: ROOT_CLASS,
      transform: (prefix, selector, prefixed) => scopeSelector(selector) ?? prefixed,
    }),
  ]).process(readFileSync(source, 'utf8'), { from: source })

  const extensionOnly = readFileSync(join(here, 'src', 'canvas', 'canvas.css'), 'utf8')
  const css = scoped.css + extensionOnly
  assertScoped(css)
  return fontImport() + css
}

const css = await buildCss()

await esbuild.build({
  entryPoints: [join(here, 'src', 'canvas', 'extension.jsx')],
  outfile: OUTFILE,
  bundle: true,
  minify: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  legalComments: 'none',
  define: {
    __ASSERT_CSS__: JSON.stringify(css),
    'process.env.NODE_ENV': '"production"',
  },
})

const built = readFileSync(OUTFILE, 'utf8')
writeFileSync(OUTFILE, `/* Generated by build-extension.mjs — do not edit. */\n${built}`)
console.log(
  `built ${relative(join(here, '..'), OUTFILE)} (${(built.length / 1024).toFixed(1)} KB)`,
)
